import sys


def solve():
    data = sys.stdin.buffer.read().split()
    t = int(data[0])
    out = []
    idx = 1
    for _ in range(t):
        n = int(data[idx])
        idx += 1
        k = n // 2

        if k % 2 == 1:
            out.append("NO")
        else:
            out.append("YES")
            evens = range(2, 2 * k + 1, 2)
            odds = list(range(1, 2 * k - 1, 2)) + [3 * k - 1]
            out.append(" ".join(map(str, evens)) + " " + " ".join(map(str, odds)))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    solve()
