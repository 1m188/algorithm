import sys


def solve():
    data = sys.stdin.buffer.read().split()
    n = int(data[0])
    k = int(data[1])

    # n>=1, k>=1时总有解：对角矩阵，每个对角元素为k
    out = []
    for i in range(n):
        row = ["0"] * n
        row[i] = str(k)
        out.append(" ".join(row))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    solve()
