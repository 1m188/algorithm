import sys

MOD = 10**9 + 7
INV3 = pow(3, MOD - 2, MOD)


def solve():
    data = sys.stdin.buffer.read().split()
    k = int(data[0])

    # 神奇对条件: (a AND b) < (a XOR b)
    # 等价于: a和b的最高不同位高于最高相同位
    # 即: 最高不同位j之上，a和b的位都为0
    # 对每个j(0..k-1): 高位全0, 第j位a=0,b=1, 低位任意 → 4^j种
    # 答案 = sum(4^j, j=0..k-1) = (4^k - 1) / 3
    ans = (pow(4, k, MOD) - 1) * INV3 % MOD
    print(ans)


if __name__ == "__main__":
    solve()
