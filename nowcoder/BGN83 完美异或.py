import sys


def solve():
    data = sys.stdin.buffer.read().split()
    t = int(data[0])
    out = []
    for i in range(t):
        n = int(data[i + 1])
        if n % 2 == 1:
            # n个1，异或和=1，n mod 1=0
            out.append(" ".join(["1"] * n))
        else:
            # 1个1 + (n-1)个3，异或和=1⊕3=2，n mod 2=0
            out.append("1 " + " ".join(["3"] * (n - 1)))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    solve()
