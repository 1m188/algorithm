import sys


def solve():
    data = sys.stdin.buffer.read().split()
    t = int(data[0])
    out = []
    for i in range(t):
        x = int(data[2 * i + 1])
        y = int(data[2 * i + 2])
        z = x ^ y
        # 答案 = z的最低设置位 = 2^k，k为z中最低1的位置
        # 公共子段a[i..i+m-1]=b[j..j+m-1]等价于(i+k)^(j+k)=z对k=0..m-1成立
        # 这要求n^(n+d)=z对连续m个n成立，最大m即为z的最低设置位
        ans = z & (-z)
        out.append(str(ans))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    solve()
