import sys

MOD = 10**9 + 7
MAXN = 10**5

# 预计算
# l[n]: S_n的长度, c[n]: S_n中'1'的个数, f[n]: S_n中逆序对数量
l = [0] * (MAXN + 1)
c = [0] * (MAXN + 1)
f = [0] * (MAXN + 1)

l[1] = 1
c[1] = 0
f[1] = 0
l[2] = 1
c[2] = 1
f[2] = 0

for i in range(3, MAXN + 1):
    l[i] = (l[i - 1] + l[i - 2]) % MOD
    c[i] = (c[i - 1] + c[i - 2]) % MOD
    # f(n) = f(n-2) + f(n-1) + c(n-2) * (l(n-1) - c(n-1))
