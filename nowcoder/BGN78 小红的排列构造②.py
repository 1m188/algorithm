import sys


def solve():
    data = sys.stdin.buffer.read().split()
    n = int(data[0])
    s = data[1].decode()

    # 整个数组是1~n的排列，所以s[n-1]必须为1
    if s[n - 1] != "1":
        print(-1)
        return

    # 找到所有s[i]=1的位置，将排列分成若干段
    # 每段内s=0的位置，前缀不能构成排列
    # 构造：每段放最大值在最前面，其余升序
    # 这样任何真前缀都包含超出范围的值，不会构成排列
    result = [0] * n
    prev = -1

    for i in range(n):
        if s[i] == "1":
            start = prev + 1
            end = i
            a = start + 1
            b = end + 1
            if a == b:
                result[start] = a
            else:
                result[start] = b
                for j in range(a, b):
                    result[start + 1 + (j - a)] = j
            prev = i

    print(" ".join(map(str, result)))


if __name__ == "__main__":
    solve()
