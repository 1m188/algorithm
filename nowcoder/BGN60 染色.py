import sys


def solve():
    data = sys.stdin.buffer.read().split()
    n = int(data[0])
    m = int(data[1])

    diff = [[0] * (n + 2) for _ in range(3)]

    idx = 2
    for _ in range(m):
        l = int(data[idx])
        r = int(data[idx + 1])
        k = int(data[idx + 2])
        idx += 3
        diff[k - 1][l] += 1
        diff[k - 1][r + 1] -= 1

    ans = 0
    cnt = [0, 0, 0]
    for i in range(1, n + 1):
        for c in range(3):
            cnt[c] += diff[c][i]
        # 绿色 = {1,2} = 有黄色且有蓝色且无红色
        if cnt[0] > 0 and cnt[1] > 0 and cnt[2] == 0:
            ans += 1

    print(ans)


if __name__ == "__main__":
    solve()
