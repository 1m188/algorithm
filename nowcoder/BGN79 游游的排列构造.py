import sys


def solve():
    data = sys.stdin.buffer.read().split()
    n = int(data[0])
    k = int(data[1])

    result = [0] * n

    # 好元素放在位置0,2,4,...,2k-2（0-indexed），值为n-k+1,...,n（递增）
    for i in range(k):
        result[2 * i] = n - k + 1 + i

    # 非好元素位置填充1,...,n-k（均小于前一个好元素，不会产生新好元素）
    val = 1
    for i in range(n):
        if result[i] == 0:
            result[i] = val
            val += 1

    print(" ".join(map(str, result)))


if __name__ == "__main__":
    solve()
