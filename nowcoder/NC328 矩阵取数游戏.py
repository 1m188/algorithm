from typing import List

MOD = 10**9 + 7


class Solution:
    def matrixScore(self, matrix: List[List[int]]) -> int:
        n = len(matrix)
        m = len(matrix[0])

        pow2 = [1] * (m + 1)
        for i in range(1, m + 1):
            pow2[i] = pow2[i - 1] * 2

        total = 0
        for row in matrix:
            # dp[l][r]: 取区间[l,r]内元素能获得的最大得分
            # 剩余r-l+1个元素，已取m-(r-l+1)个，当前是第m-r+l次取数
            dp = [[0] * m for _ in range(m)]
            for i in range(m):
                dp[i][i] = row[i] * pow2[m]
            for length in range(2, m + 1):
                for l in range(m - length + 1):
                    r = l + length - 1
                    turn = m - r + l
                    dp[l][r] = max(
                        dp[l + 1][r] + row[l] * pow2[turn],
                        dp[l][r - 1] + row[r] * pow2[turn],
                    )
            total += dp[0][m - 1]

        return total % MOD
