import sys


def solve():
    data = sys.stdin.buffer.read().split()
    n = int(data[0])

    MAX_POS = 10**6 + 2
    diff = [0] * (MAX_POS + 1)

    idx = 1
    for _ in range(n):
        a = int(data[idx])
        b = int(data[idx + 1])
        idx += 2
        diff[a] += 1
        diff[b + 1] -= 1

    ans = 0
    cur = 0
    for i in range(MAX_POS):
        cur += diff[i]
        if cur > ans:
            ans = cur

    print(ans)


if __name__ == "__main__":
    solve()
